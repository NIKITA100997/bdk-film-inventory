# Раздел про цифровой аналог бумажной "Ежедневки" — пилот только на этом
# участке (пользователь ограничил первую версию именно им); остальные
# участки принимают отчёт без рулона, как и раньше. Хардкод конкретного
# кода участка, а не отдельный флаг на Area — единственный участок в
# скоупе, расширять на другие сознательно отложено (см. план). Общий модуль,
# а не приватная константа одного роутера — используется и в api/production.py
# (отчёт требует рулон), и в api/units.py (возврат рулона требует отчёт).
AREA_REQUIRES_ROLL_ON_REPORT = "okutka_tsargovykh"

# Раздел про допуск по ширине штрипса — раньше ширина считалась
# подходящей строке задания ТОЛЬКО при точном совпадении или членстве в
# вручную заведённой группе аналогов (см. equivalent_widths); живой
# случай — привязку выданного штрипса к строке (units.py::link_task_line)
# не давало сделать из-за пары мм расхождения, для которой аналог никто
# не заводил. Общий допуск ±WIDTH_TOLERANCE_MM — как ещё один
# ДОПОЛНИТЕЛЬНЫЙ способ пройти проверку (см. _validate_matches_task_line),
# аналоги ширин по-прежнему работают отдельно поверх него (для расхождений
# шире допуска, где ширины всё равно взаимозаменяемы по факту).
WIDTH_TOLERANCE_MM = 5.0

# Раздел про рулон/штрипс — живая путаница: "рулон" в системе означало
# просто is_strip=False, без всякой связи с реальной шириной или тем,
# резали единицу или нет. Настоящий рулон — цельная, ещё не тронутая
# поставка от производителя (ширина от MIN_ROLL_WIDTH_MM); как только по
# единице прошёл хоть один рез (по длине или по ширине) или списание —
# она навсегда штрипс, даже если формально ширина осталась широкой.
# Используется в units.py (приёмка, вся резка, возврат, списание,
# излишек при инвентаризации) — единая точка правды вместо ручного флага,
# который никто не обновлял по ходу жизни единицы.
MIN_ROLL_WIDTH_MM = 1200.0
