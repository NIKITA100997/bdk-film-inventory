import { Form, DatePicker } from "antd";
import dayjs from "dayjs";

interface Props {
  /** Название поля формы — по умолчанию "occurred_at" (совпадает с
   * именем в payload на бэкенде, чтобы submit-обработчику не пришлось
   * переименовывать вручную). */
  name?: string;
  /** Кастомная подпись — например "Дата выдачи"/"Дата приёмки" вместо
   * общей формулировки, там где это понятнее по контексту формы. */
  label?: string;
}

/** Раздел про дату операции задним числом — переиспользуемое поле для
 * всех форм, пишущих в журнал движений (приём/раскрой/резка/выдача/
 * возврат/списание/инвентаризация). Пусто = "сейчас" (как было раньше),
 * бэкенд сам не даёт выбрать будущую дату — тут же дублируем то же
 * ограничение, чтобы не показывать ошибку только после отправки. */
export default function OccurredAtField({ name = "occurred_at", label = "Дата операции (необязательно — по умолчанию сейчас)" }: Props) {
  return (
    <Form.Item name={name} label={label}>
      <DatePicker
        style={{ width: "100%" }}
        format="DD.MM.YYYY"
        placeholder="Сейчас"
        disabledDate={(d) => d.isAfter(dayjs(), "day")}
      />
    </Form.Item>
  );
}
