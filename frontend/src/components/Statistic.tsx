import { Statistic as AntStatistic, type StatisticProps } from "antd";

// Раздел про неправильный подсчёт квадратуры на карточке материала —
// AntD Statistic по умолчанию группирует разряды запятой и отделяет
// дробную часть точкой (decimalSeparator: ".", groupSeparator: ",") —
// английская типографика. В русской же запятая — десятичный разделитель,
// поэтому то же число (4704 м²) отображалось как "4,704 м²", что читается
// как 4,704 (четыре целых семьсот четыре тысячных) — на три порядка
// меньше настоящего остатка. Пробел на разряды и запятая на дробную часть
// — по всему приложению, не точечно на одном экране: та же путаница ждала
// бы на любом другом Statistic с четырёхзначным и больше значением.
export default function Statistic(props: StatisticProps) {
  return <AntStatistic groupSeparator=" " decimalSeparator="," {...props} />;
}
